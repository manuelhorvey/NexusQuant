def test_results() -> Dict:
    """Run the focused Stage-10 test suites and report the outcome."""
    suites = ["tests.test_stage10", "tests.test_opportunity", "tests.test_plan"]
    total = {"tests": 0, "ok": 0, "failures": 0, "errors": 0, "skipped": 0}
    details = []
    for suite in suites:
        try:
            proc = subprocess.run(
                [sys.executable, "-m", "unittest", suite],
                capture_output=True,
                text=True,
                cwd=str(Path(__file__).parent.parent.parent),
            )
            out = proc.stdout + proc.stderr
            # parse the summary line "Ran N tests ... OK/FAILED"
            import re

            m = re.search(r"Ran (\d+) tests? in [\d.]+s", out)
            ran = int(m.group(1)) if m else 0
            ok = "OK" in out and "FAILED" not in out
            details.append(
                {
                    "suite": suite,
                    "ran": ran,
                    "ok": ok,
                    "summary": out.strip().splitlines()[-1]
                    if out.strip()
                    else "no output",
                }
            )
            total["tests"] += ran
            total["ok"] += ran if ok else 0
            total["failures"] += 0 if ok else ran
        except Exception as exc:  # pragma: no cover
            details.append({"suite": suite, "error": str(exc)})
    return {"details": details, "total": total}


