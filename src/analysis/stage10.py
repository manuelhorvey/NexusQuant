# 6. Target-level economics (Section 6/7 of the report)
# ---------------------------------------------------------------------------


def target_level_economics(trace: List[Dict]) -> Dict:
    """Per-order economics under the ACTUAL 1/3-1/3-1/3 allocation:
    expected R before/after costs, cost break-even, and the comparison vs
    the ranking EV that produced the order."""
    rows = []
    n_negative = 0
    for r in trace:
        ev_alloc = r.get("ev_alloc")
        if ev_alloc is None:
            ev_alloc = _recompute_alloc(r)
        if ev_alloc is not None and ev_alloc < 0:
            n_negative += 1
        rows.append(
            {
                "symbol": r["symbol"],
                "side": r.get("order_side"),
                "family": r.get("family"),
                "ev_ranking": r.get("ev_ranking"),
                "ev_target_level": r.get("ev_target"),
                "ev_alloc_1_3": ev_alloc,
                "cost_r": r.get("cost_r"),
                "break_even_r": r.get("break_even"),
                "edge_survives_realistic_cost": (ev_alloc is not None and ev_alloc > 0),
                "verdict_under_target_level_ev": "REJECT"
                if (ev_alloc is not None and ev_alloc <= 0)
                else "?"
                if ev_alloc is None
                else "ACCEPT",
            }
        )
    return {
        "rows": rows,
        "n_orders": len(rows),
        "n_negative_after_costs": n_negative,
        "conclusion": (
            f"{n_negative}/{len(rows)} orders have negative allocation-weighted "
            "target-level EV after realistic costs - the ranking EV that "
            "produced them (+0.5R..+2.2R) overstates the economics the ladder "
            "actually delivers."
        ),
    }


def _recompute_alloc(r: Dict) -> Optional[float]:
    """Fallback recompute when the artifact lacks ev_alloc."""
    tp = load_target_probs()
    fam = r.get("family")
    fams = (tp or {}).get("families") or {}
    side = r.get("order_side") or "long"
    dist = fams.get(fam) or (tp or {}).get(side)
    if not dist:
        return None
    rungs = [r.get("tp1_rr"), r.get("tp2_rr"), r.get("tp3_rr")]
    rungs = [x for x in rungs if x is not None] or [0.0]
    while len(rungs) < 3:
        rungs.append(0.0)
    return allocation_weighted_ev(
        dist.get("tp1"),
        dist.get("tp2"),
        dist.get("tp3"),
        dist.get("sl"),
        rungs=tuple(rungs[:3]),
        cost_r=r.get("cost_r") or 0.0,
    )


