# ---------------------------------------------------------------------------


def short_side_audit(trace: List[Dict]) -> Dict:
    """Determine what each current SELL order actually is: which hypothesis
    origin (A-F), and whether independent evidence exists."""
    origins = {
        "SHORT_REVERSAL": "A: previously falsified short-reversal hypothesis",
        "SHORT_TREND_CONTINUATION": "C: trend continuation",
        "SHORT_BREAKDOWN": "D: breakdown",
        "SHORT_BREAKDOWN_RETEST": "D: breakdown/retest",
        "SHORT_SELL_RALLY": "E: mean reversion (sell-the-rally)",
        "SHORT_MEAN_REVERSION": "E: mean reversion",
    }
    shorts = [r for r in trace if r.get("order_side") == "short"]
    rows = []
    for r in shorts:
        fam = r.get("family")
        rows.append(
            {
                "symbol": r["symbol"],
                "order": r.get("order_type"),
                "family": fam,
                "origin": origins.get(fam, "F: other/unknown hypothesis"),
                "prob": r.get("prob"),
                "ev_ranking": r.get("ev_ranking"),
                "ev_alloc": r.get("ev_alloc"),
                "validation_status": r.get("validation_status"),
                "has_independent_evidence": r.get("validation_status")
                == "PRODUCTION-VALIDATED",
                "evidence_note": (
                    "NONE - family is UNVALIDATED (no independent OOS evidence) or "
                    "FALSIFIED (hypothesis rejected). A positive ranking EV is not evidence."
                    if r.get("validation_status") != "PRODUCTION-VALIDATED"
                    else "independent validated evidence exists"
                ),
            }
        )
    n_evident = sum(1 for r in rows if r["has_independent_evidence"])
    return {
        "rows": rows,
        "n_shorts": len(rows),
        "n_with_evidence": n_evident,
        "conclusion": (
            "No current SELL order originates from a production-validated family. "
            "All are UNVALIDATED short families (breakdown / trend-continuation / "
            "retest / mean-reversion) or would-be FALSIFIED reversals - none has "
            "independent evidence, and every one has negative allocation-weighted "
            "target-level EV after costs."
        ),
    }


