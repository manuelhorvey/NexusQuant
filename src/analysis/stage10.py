def main(argv: Optional[List[str]] = None) -> int:
    import argparse

    parser = argparse.ArgumentParser(
        description="Stage-10 live opportunity attribution & production safety audit"
    )
    parser.add_argument(
        "--audit",
        action="store_true",
        help="run the audit sections and print the key numbers (no doc write)",
    )
    parser.add_argument(
        "--tests",
        action="store_true",
        help="run the Stage-10 focused test suites",
    )
    parser.add_argument(
        "--regenerate",
        action="store_true",
        help="recompute the order evidence from the live pipeline (slow)",
    )
    parser.add_argument(
        "--all",
        action="store_true",
        help="regenerate evidence + audit + focused tests + write the doc",
    )
    args = parser.parse_args(argv)

    if args.regenerate or args.all:
        print("Regenerating order evidence (16 symbols, full pipeline)...")
        regenerate_orders()

    if args.tests or args.all:
        res = test_results()
        for d in res["details"]:
            mark = "OK" if d.get("ok") else "FAIL"
            print(
                f"  [{mark}] {d.get('suite')}: {d.get('ran', '-')} tests - {d.get('summary', '')}"
            )
        print(f"  total: {res['total']['tests']} tests")

    rep = build_report()
    if args.audit:
        print("=" * 72)
        print("STAGE-10 AUDIT (key numbers)")
        print("=" * 72)
        tl = rep["target_level"]
        print(
            f"Orders with negative allocation-weighted EV after costs: {tl['n_negative_after_costs']}/{tl['n_orders']}"
        )
        print(
            f"Misleading ladder-best R:R headlines: {rep['rr_audit']['n_misleading']}/{rep['rr_audit']['n_total']}"
        )
        print(
            f"Short orders with independent evidence: {rep['short_audit']['n_with_evidence']}/{rep['short_audit']['n_shorts']}"
        )
        print("Arbitration (correct verdict per order):")
        for r in rep["arbitration"]["rows"]:
            print(
                f"  {r['symbol']:<8} book={r['book_verdict']:<6} -> FLAT ({r['family_status']})"
            )
        return 0

    out = write_doc(rep)
    print(f"Wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
