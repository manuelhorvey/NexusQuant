def write_doc(rep: Optional[Dict] = None) -> Path:
    rep = rep or build_report()
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text(render_doc(rep))
    return REPORT_PATH


