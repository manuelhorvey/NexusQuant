def order_trace() -> List[Dict]:
    """Reconstruct each order's full decision chain from the evidence.

    data timestamp -> features -> regime -> family -> prob -> entry/stop ->
    TP ladder -> target probabilities -> ranking EV -> target-level EV ->
    allocation EV -> costs -> validation status -> final decision.
    """
    orders = load_orders()
    rows = []
    for o in orders:
        if o.get("error"):
            rows.append({"symbol": o["symbol"], "error": o["error"]})
            continue
        side = o["book_verdict"].get("direction") if o.get("book_verdict") else None
        # The ORDER side is the side the live run actually produced (from
        # CURRENT_ORDERS - stable even after regeneration flips the plan
        # action to the corrected NO-SETUP/FLAT verdict). Independent of
        # the book verdict - the audit must compare the two.
        orig = next(
            (t for t in CURRENT_ORDERS if t[0] == o["symbol"]),
            (o["symbol"], None, None),
        )
        order_type = orig[1] or o.get("plan_action") or ""
        order_side = orig[2] or (
            "long"
            if str(order_type).startswith("BUY")
            else "short"
            if str(order_type).startswith("SELL")
            else None
        )
        opp = o.get(order_side or "long") or {}
        ladder = o.get("targets" if order_side == "long" else "short_targets") or {}
        rows.append(
            {
                "symbol": o["symbol"],
                "date": o.get("last_date"),
                "close": o.get("close"),
                "regime": o.get("regime"),
                "order_type": order_type,
                "order_side": order_side,
                "book_side": side,
                "book_status": (o.get("book_verdict") or {}).get("status"),
                "family": opp.get("family"),
                "family_score": opp.get("score"),
                "validation_status": opp.get("status")
                or family_status(opp.get("family")),
                "prob": opp.get("prob"),
                "entry": (opp.get("entry") or [None])[0],
                "stop": opp.get("stop"),
                "tp1_rr": _rung_rr(ladder, 0),
                "tp2_rr": _rung_rr(ladder, 1),
                "tp3_rr": _rung_rr(ladder, 2),
                "best_rr": ladder.get("best_rr"),
                "entry_type": opp.get("entry_type"),
                "ev_ranking": opp.get("ev_ranking"),
                "ev_target": opp.get("ev_target"),
                "ev_alloc": opp.get("ev_alloc"),
                "cost_r": opp.get("cost_r"),
                "break_even": opp.get("break_even"),
                "rejection": opp.get("rejected"),
            }
        )
    return rows


def _rung_rr(ladder: Dict, i: int) -> Optional[float]:
    ts = ladder.get("targets") or []
    if i < len(ts):
        return ts[i].get("rr")
    return None


def load_target_probs() -> Optional[Dict]:
    if TARGET_PROBS_JSON.exists():
        try:
            return json.loads(TARGET_PROBS_JSON.read_text())
        except Exception:
            return None
    return None


