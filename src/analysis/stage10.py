def family_census() -> List[Dict]:
    """Per-family classification from the census's per-family target-level
    TP table + the campaign's stage evidence.

    Classifications: PRODUCTION-VALIDATED / PROMISING-SHADOW-ONLY /
    UNVALIDATED / FALSIFIED / INSUFFICIENT-DATA.
    """
    tp = load_target_probs()
    fams = (tp or {}).get("families") or {}
    out = []
    all_families = sorted(set(FAMILY_STATUS) | set(fams.keys()))
    for fam in all_families:
        t = fams.get(fam) or {}
        n = t.get("n", 0)
        if n:
            ev0 = round(
                t.get("tp1", 0) * 1
                + t.get("tp2", 0) * 2
                + t.get("tp3", 0) * 3
                - t.get("sl", 0),
                4,
            )
        else:
            ev0 = None
        status = family_status(fam)
        note = _family_evidence_note(fam, status, ev0, n)
        out.append(
            {
                "family": fam,
                "n": n,
                "p_tp1": t.get("tp1"),
                "p_tp2": t.get("tp2"),
                "p_tp3": t.get("tp3"),
                "p_sl": t.get("sl"),
                "target_level_ev_0": ev0,
                "status": status,
                "note": note,
            }
        )
    return out


def _family_evidence_note(fam: str, status: str, ev0: Optional[float], n: int) -> str:
    if status == FALSIFIED:
        return (
            "Stage-6: SHORT reversal falsified (perm p=0.38, shuffled timing "
            "== signal, untouched -0.77R). Hard-rejected in production."
        )
    if status == PROMISING_SHADOW_ONLY:
        return (
            "Stage-9: LONG reversal B. PROMISING BUT INSUFFICIENT EVIDENCE - "
            "OOS n=163 +0.347R perm p=0.007, but fresh-window gate UNRESOLVED "
            "(data ends 2026-08-13). SHADOW-ONLY until new observations."
        )
    if n < 30:
        return f"insufficient resolved samples ({n}) for a validation claim"
    if ev0 is not None and ev0 <= 0:
        return (
            "no positive target-level EV at zero cost; negative after "
            "realistic costs - UNVALIDATED"
        )
    return (
        "positive gross target-level EV but no independent OOS evidence at "
        "the family level (census is descriptive, not a validation study) - UNVALIDATED"
    )


