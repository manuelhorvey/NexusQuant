def load_orders() -> List[Dict]:
    """The audit's per-symbol evidence (regenerated by
    ``regenerate_orders()`` when the artifact is missing)."""
    if ORDERS_JSON.exists():
        return json.loads(ORDERS_JSON.read_text())
    return regenerate_orders()


def regenerate_orders() -> List[Dict]:
    """Recompute the full report + opportunity book for the 16 symbols."""
    from src.data.loader import clean_data, load_data
    from src.features.indicators import add_all_indicators
    from src.features.regime import detect_regime
    from src.analysis.report import generate_full_report

    rows = []
    for sym, _, _ in CURRENT_ORDERS:
        try:
            path = _data_path(sym, "data/raw", "full_fx", "D1")
            df = clean_data(load_data(path, symbol=sym))
            df = add_all_indicators(df)
            df = detect_regime(df)
            rep = generate_full_report(
                df, symbol=sym, group="full_fx", data_dir="data/raw"
            )
            rows.append(_simplify_report(rep))
        except Exception as exc:  # pragma: no cover - diagnostic
            rows.append({"symbol": sym, "error": str(exc)})
    ORDERS_JSON.parent.mkdir(parents=True, exist_ok=True)
    ORDERS_JSON.write_text(json.dumps(rows, indent=1, default=str))
    return rows


def _simplify_report(rep: Dict) -> Dict:
    """Reduce a full report to the audit's evidence fields."""

    def num(x):
        try:
            return None if x is None else round(float(x), 6)
        except (TypeError, ValueError):
            return x

    ob = rep.get("opportunity_book") or {}
    out = {
        "symbol": rep["symbol"],
        "last_date": rep.get("last_date"),
        "close": rep.get("last_close"),
        "regime": (rep.get("regime") or {}).get("regime"),
        "plan_action": (rep.get("plan") or {}).get("action"),
        "book_verdict": ob.get("verdict"),
    }
    for side in ("long", "short"):
        opp = ob.get(side) or {}
        out[side] = {
            "family": opp.get("setup_family"),
            "score": opp.get("family_score"),
            "prob": opp.get("probability"),
            "ev_ranking": opp.get("expected_r"),
            "ev_target": opp.get("ev_target_level"),
            "ev_alloc": opp.get("expected_r_alloc"),
            "cost_r": opp.get("cost_r"),
            "break_even": opp.get("cost_break_even"),
            "status": opp.get("validation_status"),
            "rr": opp.get("rr"),
            "entry_type": opp.get("entry_type"),
            "entry": opp.get("entry_zone"),
            "stop": opp.get("invalidation"),
            "target": opp.get("target"),
            "taken": opp.get("taken"),
            "reasons": opp.get("reasons") or [],
            "rejected": opp.get("rejection_reasons") or [],
        }
    for key in ("targets", "short_targets"):
        ldr = rep.get(key) or {}
        out[key] = {
            "best_rr": ldr.get("best_rr"),
            "min_rr_tp": ldr.get("min_rr_tp"),
            "targets": [
                {
                    "t": t.get("target"),
                    "price": num(t.get("price")),
                    "rr": t.get("rr"),
                    "src": t.get("source"),
                }
                for t in (ldr.get("targets") or [])
            ],
        }
    sc = rep.get("setup_classification") or {}
    out["classifier"] = {
        "direction": sc.get("direction"),
        "family": sc.get("setup_family"),
        "long_score": sc.get("long_score"),
        "short_score": sc.get("short_score"),
        "prob_long": sc.get("prob_long"),
        "prob_short": sc.get("prob_short"),
        "pw_rr": sc.get("pw_rr"),
        "ev": sc.get("ev"),
    }
    out["macro_gate"] = ((rep.get("macro") or {}).get("gate") or {}).get("allowed")
    out["ml"] = {
        "long": (rep.get("ml") or {}).get("prob_pct"),
        "short": (rep.get("ml_short") or {}).get("prob_pct"),
    }
    return out


