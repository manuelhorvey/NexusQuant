def _fmt(v, suffix="", nd=2):
    if v is None:
        return "-"
    try:
        if isinstance(v, float):
            return f"{v:+.2f}{suffix}" if suffix == "R" else f"{v:.{nd}f}"
        return str(v)
    except (TypeError, ValueError):
        return str(v)


